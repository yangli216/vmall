CREATE TABLE IF NOT EXISTS t_dev_payment (
  out_trade_no VARCHAR(32) PRIMARY KEY,
  buyer_openid VARCHAR(64) NOT NULL,
  total_fen INT NOT NULL,
  transaction_id VARCHAR(64) NOT NULL UNIQUE,
  trade_state VARCHAR(16) NOT NULL DEFAULT 'NOTPAY',
  refund_sn VARCHAR(64) NULL UNIQUE,
  refund_status VARCHAR(16) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
